#!/usr/bin/env python3
"""Render a service manifest into Terraform variables.

This is the boundary the whole platform rests on. Above it is intent, written
by an agent in a small enumerated schema. Below it is Terraform, generated by
this script from opinionated modules. The mapping is mechanical and total:
the same manifest always produces the same tfvars, byte for byte.

That is what makes a non-deterministic author safe. The agent's output varies;
everything downstream of this line does not.

Usage:
    python3 platform/bin/render.py services/checkout/service.yaml
    python3 platform/bin/render.py services/*/service.yaml --out deploy/
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from validate import load_yaml  # noqa: E402


def render(manifest: dict, manifest_path: str) -> dict:
    """Map a manifest onto the module's variables.

    Every key the module accepts is set explicitly. Nothing is left to a
    Terraform-side default that the manifest could have influenced, because a
    default applied in two places is a default that will eventually disagree
    with itself.
    """
    meta = manifest["metadata"]
    spec = manifest["spec"]
    runtime = spec.get("runtime", {})

    tfvars: dict = {
        "name": meta["name"],
        "environment": meta["environment"],
        "owner": meta["owner"],
        "cost_centre": meta["costCentre"],
        "manifest_path": manifest_path,
        "runtime": {
            "cpu": runtime.get("cpu", 512),
            "memory": runtime.get("memory", 1024),
            "image": runtime.get("image", "public.ecr.aws/nginx/nginx:stable"),
            "replicas": runtime.get("replicas", 2),
            "port": 80,
        },
        "permissions": {
            "capabilities": spec.get("permissions", {}).get("capabilities", []),
        },
        "observability": {
            "slo_target_percent": spec.get("observability", {}).get(
                "sloTargetPercent", 99.0
            ),
            "log_retention_days": spec.get("observability", {}).get(
                "logRetentionDays", 30
            ),
        },
    }

    ingress = spec.get("ingress")
    if ingress is not None:
        tfvars["ingress"] = {
            "public": ingress.get("public", False),
            "path": ingress.get("path", "/"),
            "health_check_path": ingress.get("healthCheckPath", "/"),
        }
    else:
        tfvars["ingress"] = None

    database = spec.get("database")
    if database is not None:
        tfvars["database"] = {
            "engine": database["engine"],
            "size": database["size"],
            "retention": database.get("retention", "7d"),
            "public": database.get("public", False),
            "multi_az": database.get("multiAz", False),
        }
    else:
        tfvars["database"] = None

    # The escape hatch. Raw module arguments merge last and deliberately win, so
    # the one percent of cases that need something unusual stay reachable. Any
    # pull request touching this block requires a platform-team reviewer, which
    # is the cost of the flexibility.
    overrides = spec.get("overrides") or {}
    if overrides:
        tfvars.update(overrides)

    return tfvars


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifests", nargs="+")
    parser.add_argument(
        "--out",
        default="deploy",
        help="directory to write <env>-<service>.tfvars.json into",
    )
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="print the rendered variables instead of writing files",
    )
    args = parser.parse_args(argv)

    out_dir = REPO / args.out
    failed = False

    for arg in args.manifests:
        path = pathlib.Path(arg)
        if not path.exists():
            print(f"SKIP    {arg} (not found)", file=sys.stderr)
            continue

        manifest = load_yaml(path)
        try:
            rel = str(path.resolve().relative_to(REPO))
        except ValueError:
            rel = str(path)

        try:
            tfvars = render(manifest, rel)
        except KeyError as exc:
            failed = True
            print(f"ERROR   {path}: missing required field {exc}", file=sys.stderr)
            continue

        body = json.dumps(tfvars, indent=2, sort_keys=True) + "\n"

        if args.stdout:
            print(f"# rendered from {rel}")
            print(body)
            continue

        out_dir.mkdir(parents=True, exist_ok=True)
        target = out_dir / f"{tfvars['environment']}-{tfvars['name']}.tfvars.json"
        target.write_text(body)

        # --out may point outside the repo, which relative_to would reject.
        try:
            shown = target.relative_to(REPO)
        except ValueError:
            shown = target
        print(f"RENDER  {rel} -> {shown}")

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
